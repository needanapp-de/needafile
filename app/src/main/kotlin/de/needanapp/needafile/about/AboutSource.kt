package de.needanapp.needafile.about

import androidx.annotation.StringRes

/** A license as shown on the about screen, with its full text bundled in assets/licenses when there is one. */
enum class SourceLicense(val spdxId: String, val isCopyleft: Boolean, val assetName: String?, val url: String) {
    GPL_3("GPL-3.0", true, "GPL-3.0.txt", "https://www.gnu.org/licenses/gpl-3.0.html"),
    AGPL_3("AGPL-3.0", true, "AGPL-3.0.txt", "https://www.gnu.org/licenses/agpl-3.0.html"),
    APACHE_2("Apache-2.0", false, "Apache-2.0.txt", "https://www.apache.org/licenses/LICENSE-2.0"),
    LGPL_2_1("LGPL-2.1", true, "LGPL-2.1.txt", "https://www.gnu.org/licenses/old-licenses/lgpl-2.1.html"),
    MIT("MIT", false, "MIT.txt", "https://opensource.org/license/mit"),
    ZERO_BSD("0BSD", false, "0BSD.txt", "https://opensource.org/license/0bsd"),
    BSD("BSD", false, null, "https://opensource.org/license/bsd-2-clause"),
}

/**
 * A project this app is based on or ships with.
 *
 * @param module Maven coordinate (group:name) whose version is looked up in the versions generated by the build,
 *               null when [version] is given directly
 * @param licenseUrl the project's own license page, for licenses without a bundled text
 * @param copyright copyright line put above the license text, for licenses that ask for it
 */
data class AboutSource(
    val name: String,
    @StringRes val descriptionRes: Int,
    val license: SourceLicense,
    val url: String,
    val module: String? = null,
    val version: String? = null,
    val licenseUrl: String? = null,
    val copyright: String? = null,
)
